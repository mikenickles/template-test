// Builder UI check: real mouse click on the title, real keys, debug overlay, Esc pause, resume.
const { launch } = require('./harness.cjs');
(async () => {
  const { browser, page, errors, shot } = await launch({ width: 1280, height: 720 });
  const out = {};
  const st = () => page.evaluate(() => { const s = __game.state(); return { phase: s.phase, x: +s.player.x.toFixed(2), y: +s.player.y.toFixed(2), z: +s.player.z.toFixed(2), crouching: s.player.crouching, onGround: s.player.onGround, drawCalls: s.drawCalls, triangles: s.triangles, fps: +s.fps.toFixed(1) }; });
  out.title = await st();
  out.titleVisible = await page.evaluate(() => getComputedStyle(document.getElementById('title')).display);
  await shot('round1/builder_title.png');
  await page.mouse.click(640, 360);
  await page.waitForTimeout(300);
  out.afterClick = await st();
  out.pointerLocked = await page.evaluate(() => !!document.pointerLockElement);
  await page.keyboard.down('KeyW'); await page.waitForTimeout(1500); await page.keyboard.up('KeyW');
  out.afterW = await st();
  await page.keyboard.down('ShiftLeft'); await page.keyboard.down('KeyW'); await page.waitForTimeout(1000); await page.keyboard.up('KeyW'); await page.keyboard.up('ShiftLeft');
  out.afterSprint = await st();
  await page.keyboard.down('KeyC'); await page.waitForTimeout(400); out.crouchC = (await st()).crouching; await page.keyboard.up('KeyC');
  await page.keyboard.down('ControlLeft'); await page.waitForTimeout(400); out.crouchCtrl = (await st()).crouching; await page.keyboard.up('ControlLeft');
  await page.waitForTimeout(300); out.crouchReleased = (await st()).crouching;
  await page.keyboard.down('Space'); await page.waitForTimeout(250); out.jump = await st(); await page.keyboard.up('Space');
  await page.keyboard.down('KeyA'); await page.waitForTimeout(500); await page.keyboard.up('KeyA'); out.afterA = await st();
  await page.keyboard.down('KeyD'); await page.waitForTimeout(500); await page.keyboard.up('KeyD'); out.afterD = await st();
  await page.keyboard.down('KeyS'); await page.waitForTimeout(500); await page.keyboard.up('KeyS'); out.afterS = await st();
  await page.keyboard.press('Backquote'); await page.waitForTimeout(600);
  out.debugText = await page.evaluate(() => document.getElementById('debug').textContent);
  out.debugShown = await page.evaluate(() => getComputedStyle(document.getElementById('debug')).display);
  await shot('round1/builder_debug_player.png');
  out.debugState = await st();
  await page.evaluate(() => { __game.setView('floor_centre'); __game.render(); }); await page.waitForTimeout(500);
  await shot('round1/builder_debug_floor_centre.png');
  await page.evaluate(() => __game.clearView());
  await page.keyboard.press('Backquote'); await page.waitForTimeout(300);
  out.debugHidden = await page.evaluate(() => getComputedStyle(document.getElementById('debug')).display);
  await page.keyboard.press('Escape'); await page.waitForTimeout(300);
  out.afterEsc = await st();
  out.pauseText = await page.evaluate(() => document.getElementById('titleGo').textContent);
  const z0 = out.afterEsc.z; await page.keyboard.down('KeyW'); await page.waitForTimeout(400); await page.keyboard.up('KeyW');
  out.movedWhilePaused = (await st()).z !== z0;
  await page.mouse.click(640, 360); await page.waitForTimeout(300);
  out.afterResume = await st();
  out.errors = errors;
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})().catch((e) => { console.error('FAILED', e); process.exit(1); });
